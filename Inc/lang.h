/*!@file
   @brief Language of the UI. The texts are written in English in the code and passed through
          tr(), which gives their translation in the chosen language (lang.c).

   @author artgameur
   @version 1.0
*/
// ------------------------------------------------------------------------------------------------

#ifndef LANG_H
#define LANG_H

// ================================================================================================
// ================================================================================================
//            DEFINE DECLARATION
// ================================================================================================
// ================================================================================================

// Language dropdown (order of Lang_t); each name in its own language
#define LANG_OPTIONS          "English\nFrançais"

// ================================================================================================
// ================================================================================================
//            ENUM DECLARATION
// ================================================================================================
// ================================================================================================

typedef enum
{
  LANG_EN,
  LANG_FR,
  LANG_COUNT,
} Lang_t;

// ================================================================================================
// ================================================================================================
//            EXTERNAL FUNCTION DECLARATION
// ================================================================================================
// ================================================================================================

// Set once at startup, before the UI is created (the texts are not updated afterwards)
void   langSet(Lang_t lang);
Lang_t langGet(void);

// Translation of an English text (same printf conversions, in the same order); the text itself
// in English or when it has no translation. The result stays valid (static).
const char * tr(const char * text);

#endif //LANG_H
